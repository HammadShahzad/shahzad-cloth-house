#!/usr/bin/env bash
# Regenerate docs/history/ISSUES-AND-PRS.md from GitHub (and optionally a monthly report skeleton).
# Run from the app repo root. Needs gh (authenticated) and jq.
#   bash scripts/history-report.sh
#   bash scripts/history-report.sh --month 2026-11
set -euo pipefail
MONTH=""; [ "${1:-}" = "--month" ] && MONTH="${2:?month like 2026-11}"
REPO="$(gh repo view --json nameWithOwner -q .nameWithOwner)"
OUT=docs/history/ISSUES-AND-PRS.md; mkdir -p docs/history/reports

lbl='[.labels[].name] | join(", ")'
asg='[.assignees[].login] | join(", ")'
{
  echo "# Issues and PRs: $REPO"
  echo
  echo "> Auto-generated by \`scripts/history-report.sh\` on $(date -u +%Y-%m-%d). Do not edit by hand; edit FEATURES.md / BUGS.md / DECISIONS.md instead."
  echo
  echo "## Open issues"
  echo "| # | Title | Labels | Assignee | Opened |"; echo "|---|---|---|---|---|"
  gh issue list -R "$REPO" --state open --limit 1000 --json number,title,labels,assignees,createdAt \
    | jq -r ".[] | \"| #\(.number) | \(.title|gsub(\"\\\\|\";\"/\")) | \($lbl) | \($asg) | \(.createdAt[0:10]) |\""
  echo
  echo "## Closed issues"
  echo "| # | Title | Labels | Closed |"; echo "|---|---|---|---|"
  gh issue list -R "$REPO" --state closed --limit 1000 --json number,title,labels,closedAt \
    | jq -r ".[] | \"| #\(.number) | \(.title|gsub(\"\\\\|\";\"/\")) | \($lbl) | \(.closedAt[0:10]) |\""
  echo
  echo "## Open PRs"
  echo "| # | Title | Branch → Base | Author | Opened |"; echo "|---|---|---|---|---|"
  gh pr list -R "$REPO" --state open --limit 1000 --json number,title,headRefName,baseRefName,author,createdAt \
    | jq -r '.[] | "| #\(.number) | \(.title|gsub("\\|";"/")) | \(.headRefName) → \(.baseRefName) | \(.author.login) | \(.createdAt[0:10]) |"'
  echo
  echo "## Merged PRs"
  echo "| # | Title | Base | Author | Merged |"; echo "|---|---|---|---|---|"
  gh pr list -R "$REPO" --state merged --limit 1000 --json number,title,baseRefName,author,mergedAt \
    | jq -r '.[] | "| #\(.number) | \(.title|gsub("\\|";"/")) | \(.baseRefName) | \(.author.login) | \(.mergedAt[0:10]) |"'
} > "$OUT"
echo "wrote $OUT"

if [ -n "$MONTH" ]; then
  R="docs/history/reports/$MONTH.md"
  if [ -e "$R" ]; then echo "$R exists, not overwritten"; exit 0; fi
  {
    echo "# Monthly report: $REPO, $MONTH"; echo
    echo "## Summary (3 bullets)"; echo "- "; echo
    echo "## Merged PRs this month"; echo "| # | Title | Base |"; echo "|---|---|---|"
    gh pr list -R "$REPO" --state merged --limit 1000 --search "merged:$MONTH" --json number,title,baseRefName \
      | jq -r '.[] | "| #\(.number) | \(.title|gsub("\\|";"/")) | \(.baseRefName) |"'
    echo; echo "## Issues closed this month"; echo "| # | Title | Labels |"; echo "|---|---|---|"
    gh issue list -R "$REPO" --state closed --limit 1000 --search "closed:$MONTH" --json number,title,labels \
      | jq -r ".[] | \"| #\(.number) | \(.title|gsub(\"\\\\|\";\"/\")) | \($lbl) |\""
    echo; echo "## Open bugs by priority"
    for p in P0 P1 P2 P3; do echo "- $p: $(gh issue list -R "$REPO" --state open --label type:bug --label $p --limit 1000 --json number | jq length)"; done
    echo; echo "## Roadmap progress"; echo "- "; echo; echo "## Next month"; echo "- "
  } > "$R"
  echo "wrote $R"
fi
